//ініціалізація АЦП
void init_ACP_(void)
{
  
    // дозвіл глобального тактування модуля ADC
    RCC->APB2ENR |= RCC_APB2ENR_ADCEN;
    
    // задати точність даних
    //00-12біт
    
    // задати вирівнювання даних
    ADC1->CFGR1&=~BIT5; //вирівнювання по правому краю
    
    //12 біт розряд
    ADC1->CFGR1&=~BIT3; //вирівнювання по правому краю
    ADC1->CFGR1&=~BIT4; //вирівнювання по правому краю
    
    // задати канал вимірювання
    ADC1->CHSELR|=BIT5;//обраний для вимірювання 5 канал 
      
    // задати швидкість обрахунку
    ADC1->SMPR=0x07; // обрахунок здійснюється за 239.5 ADC clock cycles (близько 96000 вибірок за секунду)
    
    // задати джерело тактування для АЦП: PCLK/4
    ADC1->CFGR2|=BIT31;
    
    // 
    ADC1->CR|=ADCAL_;
    
    // 
    while(ADC1->CR&ADCAL_);
    
    // увімкнення модуля
    ADC1->CR|=ADEN_; 
    
    // дозвіл переривань при події обрахунку канала
    //ADC1->IER|=EOCIE_;
    
    // глобально дозвіл переривань для I2C1 в регістрі VIC
    //NVIC_EnableIRQ(ADC1_IRQn_);//Дозволяємо переривання в NVIC для I2C1      

      
    ADC1->CR|=BIT2;//старт обрахунку
    ADC1->ISR|=BIT1;      //зкидання прапора закінчення обрахунку 
    ADC1->CR|=BIT2;       //старт обрахунку АЦП
    
    //ADC1->ISR|=BIT1;//зкидання прапора закінчення обрахунку 
    //ADC1->CR|=BIT2; //старт обрахунку АЦП
}

